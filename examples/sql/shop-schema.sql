-- Sample shop database for the realistic examples (order-pipeline, daily-sales-report, export-worker).
-- Works on H2 and PostgreSQL.
--
-- Quick start with MiniFlow's own H2 database:
--   1. Start MiniFlow with MINIFLOW_H2_CONSOLE=true and open http://localhost:8080/h2-console
--      (JDBC URL: jdbc:h2:file:./data/miniflow, user: sa, empty password)
--   2. Paste and run this file.
--   3. Create a "Database" credential named "shop-db" with the same JDBC URL, user "sa", empty password.
-- For a real shop, point "shop-db" at your shop's database instead (read-only user recommended for reports).

CREATE TABLE IF NOT EXISTS shop_orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no       VARCHAR(40)    NOT NULL UNIQUE,
    customer_name  VARCHAR(200),
    customer_email VARCHAR(200)   NOT NULL,
    total          DECIMAL(12, 2) NOT NULL,
    currency       VARCHAR(3)     NOT NULL DEFAULT 'EUR',
    status         VARCHAR(20)    NOT NULL DEFAULT 'NEW',
    created_at     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_shop_orders_created ON shop_orders (created_at);
CREATE INDEX IF NOT EXISTS idx_shop_orders_email ON shop_orders (customer_email);

